-- =============================================================
-- 11_plant_zone_map.sql
-- Phase 1 of the multi-plant Template Adapter Layer.
--
-- Purpose: let a plant that does not share AAT/FTM's zone
-- naming/sequence be onboarded by DATA (mapping rows, approved by a
-- human) instead of by CODE. Written before either plant was
-- onboarded; SAP has since gone through this path (Phase 4,
-- sql/13_sap_plant.sql - all 32 P703 zones proposed, reviewed, and
-- approved). FVL remains investigation-only (Phase 5) - not because
-- this mechanism doesn't apply to it, but because it has no Serial
-- No./Paintline data at all (see point 2 below), which is a separate,
-- unresolved problem this table does not solve.
--
-- This file is purely ADDITIVE:
--   - no existing table is dropped
--   - no existing row in wavescan is touched
--   - AAT/FTM keep every protection they have today
--
-- Three changes:
--
--   1. ref_plant_zone_map
--        (plant, model, raw_zone_text) -> canonical zone_code
--        Every non-AAT/FTM zone spelling must be approved here
--        before it can be loaded. Proposals may be generated by
--        the adapter, but nothing is used until approved_by is set.
--
--   2. ref_plant.requires_serial
--        AAT/FTM/SAP genuinely identify a vehicle by serial number.
--        FVL's export does not populate Serial No. at all (measured
--        and confirmed: 1504/1504 rows blank in the July file).
--        Rather than weaken serial_no for every plant, the column
--        becomes NULLABLE and the LOADER enforces "must have a
--        serial" only for plants where requires_serial = true.
--        AAT/FTM/SAP keep full protection; only FVL is exempted,
--        and only because it has no serial to give.
--
--   3. wavescan.src_zone_text / src_zone_no
--        Provenance columns. What the plant actually wrote and
--        what number it used, kept alongside the canonical
--        checkzone so every row can be traced back to its source
--        and a wrong mapping can be found and corrected later.
--
-- Run against: paint_appearance
-- Re-runnable: safe to run more than once (IF NOT EXISTS / DROP IF EXISTS).
-- =============================================================


-- -------------------------------------------------------------
-- 1. Per-plant zone mapping (human-approved). Used by SAP's
--    onboarding (Phase 4); available to any future plant, including
--    FVL once it has an identity column to load against.
-- -------------------------------------------------------------
DROP TABLE IF EXISTS ref_plant_zone_map CASCADE;

CREATE TABLE ref_plant_zone_map (
    map_id          BIGSERIAL PRIMARY KEY,

    plant_code      TEXT     NOT NULL REFERENCES ref_plant (plant_code),
    model_code      TEXT     NOT NULL REFERENCES ref_model (model_code),

    -- exactly what the plant's file contains, e.g. FVL '14ROOF',
    -- SAP '01RHS Hood Rr28'
    raw_zone_text   TEXT     NOT NULL,
    raw_position    SMALLINT,        -- leading/plant-local number, if any

    zone_code       TEXT     NOT NULL REFERENCES ref_checkzone (zone_code),

    -- how the mapping was produced - never silently trusted
    confidence      TEXT     NOT NULL DEFAULT 'PROPOSED',
    proposal_method TEXT,            -- e.g. 'tolerance+keyword-group+sequence'
    approved_by     TEXT,
    approved_at     TIMESTAMP,

    created_at      TIMESTAMP NOT NULL DEFAULT now(),
    note            TEXT,

    CONSTRAINT uq_plant_zone_map UNIQUE (plant_code, model_code, raw_zone_text),
    CONSTRAINT ck_pzm_confidence CHECK (confidence IN ('PROPOSED','APPROVED','REJECTED')),
    -- a mapping the loader may actually use must be approved by a person
    CONSTRAINT ck_pzm_approved CHECK (
        confidence <> 'APPROVED' OR (approved_by IS NOT NULL AND approved_at IS NOT NULL)
    ),
    -- zone must be valid for this model (same protection wavescan has)
    CONSTRAINT fk_pzm_model_zone FOREIGN KEY (model_code, zone_code)
        REFERENCES ref_model_zone (model_code, zone_code)
);

COMMENT ON TABLE ref_plant_zone_map IS
    'Maps a plant''s own zone label/number to the canonical zone_code. '
    'Only rows with confidence=APPROVED are used when loading. '
    'AAT/FTM do not need this table - their labels already resolve '
    'through ref_checkzone_alias.';
COMMENT ON COLUMN ref_plant_zone_map.confidence IS
    'PROPOSED = generated by the adapter, not yet trusted. '
    'APPROVED = a person confirmed it; loader may use it. '
    'REJECTED = a person confirmed it is WRONG; kept so it is not re-proposed.';
COMMENT ON COLUMN ref_plant_zone_map.proposal_method IS
    'How a PROPOSED row was generated, for audit (e.g. tolerance-group + '
    'keyword-group + within-group sequence).';

CREATE INDEX idx_pzm_plant_model ON ref_plant_zone_map (plant_code, model_code);
CREATE INDEX idx_pzm_pending     ON ref_plant_zone_map (confidence)
    WHERE confidence = 'PROPOSED';


-- -------------------------------------------------------------
-- 2. Per-plant serial requirement
-- -------------------------------------------------------------
ALTER TABLE ref_plant
    ADD COLUMN IF NOT EXISTS requires_serial BOOLEAN NOT NULL DEFAULT true;

COMMENT ON COLUMN ref_plant.requires_serial IS
    'true: the loader must reject rows with no serial_no (AAT/FTM/SAP - '
    'serial genuinely identifies the vehicle here). '
    'false: rows with a NULL serial_no are accepted (FVL - the export '
    'never populates Serial No.; confirmed 1504/1504 rows blank in the '
    'July 2026 file). Cross-file duplicate detection cannot function for '
    'a plant with requires_serial=false, because SQL NULL never equals '
    'NULL - within-file dedup on (plant, checkzone, measurements) still '
    'applies.';

-- AAT/FTM already default to true; make it explicit for the plants
-- that exist today so a reviewer never has to guess the default.
UPDATE ref_plant SET requires_serial = true WHERE plant_code IN ('AAT', 'FTM');


-- -------------------------------------------------------------
-- 3. Provenance columns on wavescan (additive, nullable)
-- -------------------------------------------------------------
ALTER TABLE wavescan
    ADD COLUMN IF NOT EXISTS src_zone_text TEXT,
    ADD COLUMN IF NOT EXISTS src_zone_no   SMALLINT;

COMMENT ON COLUMN wavescan.src_zone_text IS
    'Exactly what the source file wrote in the Checkzone column, before '
    'cleaning. NULL for rows loaded before this column existed.';
COMMENT ON COLUMN wavescan.src_zone_no IS
    'The plant-local position number parsed out of src_zone_text, if any. '
    'Provenance only - never used as identity. The same physical panel '
    'can carry different numbers on different plants/models (verified: '
    'RCROOF is #27 on P703 but #26 on U704; FVL numbers the same 7 '
    'horizontal points 1-5,11,14 where AAT/FTM use 1-5,11,27).';


-- -------------------------------------------------------------
-- 4. Relax NOT NULL so a plant with requires_serial=false (FVL)
--    can be loaded. AAT/FTM/SAP protection is NOT weakened: the
--    loader enforces "serial required" per-plant in code, reading
--    ref_plant.requires_serial, and rejects a blank serial there
--    exactly as strictly as the database rejected it before today.
-- -------------------------------------------------------------
ALTER TABLE wavescan ALTER COLUMN serial_no DROP NOT NULL;
ALTER TABLE wavescan ALTER COLUMN paintline DROP NOT NULL;

ALTER TABLE wavescan DROP CONSTRAINT IF EXISTS ck_ws_serial;
ALTER TABLE wavescan ADD CONSTRAINT ck_ws_serial
    CHECK (serial_no IS NULL OR length(trim(serial_no)) > 0);

COMMENT ON COLUMN wavescan.serial_no IS
    'Plant-local body number. NOT globally unique - always pair with '
    'plant. NULL only for plants with ref_plant.requires_serial=false '
    '(currently: none loaded yet - FVL is investigation-only). The '
    'loader, not the database, enforces "must have a serial" per plant.';
COMMENT ON COLUMN wavescan.paintline IS
    'Paint booth. NULL only for plants with ref_plant.requires_serial=false '
    '(FVL''s July export does not populate this column either).';


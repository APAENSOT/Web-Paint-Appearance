def matches(row: dict) -> bool:
    """True when one ``ref_model_alias`` row is T21 test residue.

    Pure, so the test can exercise the guard without a database: the shape
    this revision is allowed to delete, and nothing else.
    """
    import re

    return (
        row.get("plant_code") == PLANT
        and row.get("model_code") == MODEL
        and bool(re.match(RAW_PATTERN, row.get("raw_value") or ""))
        and (row.get("note") or "").startswith("approved from mapping proposal ")
        and (row.get("note") or "").endswith(" for plant AAT")
    )


def upgrade() -> None:
    conn = op.get_bind()
    before = conn.execute(text("SELECT count(*) FROM ref_model_alias")).scalar_one()
    snapshot = [
        dict(r)
        for r in conn.execute(
            text(
                "SELECT alias_id, raw_value, model_code, note, plant_code "
                "FROM ref_model_alias WHERE raw_value LIKE 'T21 %' "
                "ORDER BY alias_id"
            )
        ).mappings().all()
    ]

    # --- guard: refuse and delete nothing on any mismatch ---------------
    stray = [r for r in snapshot if not matches(r)]
    if stray:
        raise RuntimeError(
            f"T77 refused: {len(stray)} row(s) matching 'T21 %' are not test "
            f"residue, so nothing was deleted. First: {stray[0]}"
        )
    if len(snapshot) != EXPECTED:
        raise RuntimeError(
            f"T77 refused: found {len(snapshot)} 'T21 %' aliases, expected "
            f"{EXPECTED}; nothing was deleted."
        )
    if {(r["alias_id"], r["raw_value"]) for r in snapshot} != {
        (aid, raw) for aid, raw, _note in LEAKED
    }:
        raise RuntimeError(
            "T77 refused: the live 'T21 %' aliases are not the snapshot this "
            "revision carries, so downgrade could not restore them; nothing "
            "was deleted."
        )

    ids = [r["alias_id"] for r in snapshot]
    conn.execute(
        text("DELETE FROM ref_model_alias WHERE alias_id = ANY(:ids)"), {"ids": ids}
    )

    conn.execute(
        text(
            "INSERT INTO audit_event "
            "(actor_user_id, actor_type, action, entity_type, entity_id, "
            " before, after, correlation_id) "
            "VALUES (NULL, 'system', :action, 'ref_model_alias', :entity, "
            "        CAST(:before AS jsonb), CAST(:after AS jsonb), NULL)"
        ),
        {
            "action": ACTION,
            "entity": f"{PLANT}:{MODEL}",
            # The per-row `note` is deliberately left out: see the module
            # docstring (this cluster cannot store an out-of-line audit
            # value). `LEAKED` carries every note.
            "before": json.dumps(
                {
                    "deleted": [
                        {"alias_id": r["alias_id"], "raw_value": r["raw_value"]}
                        for r in snapshot
                    ]
                }
            ),
            "after": json.dumps(
                {
                    "revision": "0028",
                    "deleted_count": len(ids),
                    "plant_code": PLANT,
                    "model_code": MODEL,
                    "raw_pattern": RAW_PATTERN,
                    "reason": REASON,
                    "owner_approved": "2026-10-06",
                    "notes_in": "migration 0028 LEAKED (audit_event TOAST unavailable)",
                }
            ),
        },
    )

    left = conn.execute(
        text("SELECT count(*) FROM ref_model_alias WHERE raw_value LIKE 'T21 %'")
    ).scalar_one()
    after = conn.execute(text("SELECT count(*) FROM ref_model_alias")).scalar_one()
    if left or after != before - EXPECTED:
        raise RuntimeError(
            f"T77 post-check failed: {left} 'T21 %' rows left, total "
            f"{before} -> {after}, expected {before - EXPECTED}."
        )


def downgrade() -> None:
    """Re-insert the 61 rows with their original ids. The audit row stays."""
    conn = op.get_bind()
    for alias_id, raw_value, note in LEAKED:
        conn.execute(
            text(
                "INSERT INTO ref_model_alias "
                "(alias_id, raw_value, model_code, note, plant_code) "
                "VALUES (:id, :raw, :model, :note, :plant)"
            ),
            {"id": alias_id, "raw": raw_value, "model": MODEL, "note": note,
             "plant": PLANT},
        )
